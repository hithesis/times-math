kpse.set_program_name("lualatex")

local table_path = assert(kpse.find_file("unicode-math-table.tex"))

local by_class = {}
local total = 0
for line in io.lines(table_path) do
  local hex, name, class = line:match('\\UnicodeMathSymbol%{"([0-9A-Fa-f]+)}{\\?([%a@]+)%s*}{\\math([a-z]+)}')
  if hex then
    local cp = tonumber(hex, 16)
    by_class[class] = by_class[class] or {}
    table.insert(by_class[class], {cp = cp, name = name})
    total = total + 1
  end
end

local order = {
  "ord", "bin", "rel", "open", "close", "fence", "punct", "op",
  "alpha", "accent", "botaccent", "accentwide", "botaccentwide", "accentoverlay", "under", "over",
}
local class_title = {
  ord = "mathord",
  bin = "mathbin",
  rel = "mathrel",
  open = "mathopen",
  close = "mathclose",
  fence = "mathfence",
  punct = "mathpunct",
  op = "mathop",
  alpha = "mathalpha",
  accent = "mathaccent",
  accentwide = "mathaccentwide",
  botaccent = "mathbotaccent",
  accentoverlay = "mathaccentoverlay",
  botaccentwide = "mathbotaccentwide",
  under = "mathunder",
  over = "mathover",
}

local out = {}
out[#out + 1] = "% Generated by dev/gen-coverage.lua."
out[#out + 1] = "\\documentclass{article}"
out[#out + 1] = "\\usepackage{times-math}"
out[#out + 1] = ""
out[#out + 1] = "\\begin{document}"
out[#out + 1] = ""
out[#out + 1] = "\\section*{Full traversal of the Unicode-math symbol table (" .. total .. " entries)}"
out[#out + 1] = ""

local emitted = 0
for _, class in ipairs(order) do
  local items = by_class[class]
  if items then
    out[#out + 1] = "\\section*{" .. (class_title[class] or class) .. " (" .. #items .. ")}"
    out[#out + 1] = ""
    local class_base = (class == "accent" or class == "botaccent" or class == "accentwide"
      or class == "botaccentwide" or class == "accentoverlay" or class == "under" or class == "over")
    local function combining(cp)
      return (0x0300 <= cp and cp <= 0x036F) or (0x20D0 <= cp and cp <= 0x20FF)
        or (0x1AB0 <= cp and cp <= 0x1AFF) or (0xFE20 <= cp and cp <= 0xFE2F)
    end
    local wide = class_base
    local root_cmds = {
      sqrt = true, cuberoot = true, fourthroot = true,
      longdivision = true, longdivisionsign = true,
    }
    local line = {}
    for i, it in ipairs(items) do
      local nb = class_base or combining(it.cp)
      if root_cmds[it.name] then
        line[#line + 1] = "$\\" .. it.name .. "{x}$"
      else
        line[#line + 1] = nb and ("$\\" .. it.name .. "{a}$") or ("$\\" .. it.name .. "$")
      end
      if i < #items then
        line[#line + 1] = (wide or nb) and "\\quad{}" or " "
      end
      local per_line = wide and 8 or 16
      if #line >= per_line then
        out[#out + 1] = table.concat(line) .. "\\par"
        line = {}
      end
    end
    if #line > 0 then
      out[#out + 1] = table.concat(line) .. "\\par"
    end
    out[#out + 1] = ""
    emitted = emitted + #items
  end
end

